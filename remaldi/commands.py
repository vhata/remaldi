@dataclass(frozen=True)
class LocalAction:
    """A local action and the string parameter Vivaldi's handler reads, if any."""

    parameter: str | None
    integer: bool = False
    positive: bool = False


# Actions handled by executeLocalAction before the registry. Every allowed one
# needs its parameter: without one the handler declines and the name falls
# through to the registry and then to a chain lookup. COMMAND_OPEN_LINK is
# also a registered command, whose registry action does nothing.
LOCAL_ACTIONS = {
    "COMMAND_OPEN_LINK": LocalAction("URL"),
    "JS_LOCAL_ACTIVATE_TAB": LocalAction("tab ID", integer=True),
    "JS_LOCAL_ACTIVATE_WINDOW": LocalAction("window ID", integer=True),
    "JS_LOCAL_ACTIVATE_WORKSPACE": LocalAction("workspace ID", integer=True),
    "JS_LOCAL_ADD_ACTIVE_TAB_TO_BOOKMARKS": LocalAction("bookmark folder ID"),
    "JS_LOCAL_CLEAR_CLOSED_TABS": LocalAction(None),
    "JS_LOCAL_CLEAR_CLOSED_WEBPANELS": LocalAction(None),
    "JS_LOCAL_OPEN_SESSION": LocalAction("saved session ID", integer=True),
    "JS_LOCAL_REOPEN_CLOSED_TAB": LocalAction("closed tab ID"),
    "JS_LOCAL_REOPEN_CLOSED_WINDOW": LocalAction("closed window session ID"),
    "JS_LOCAL_RESTORE_WEBPANEL": LocalAction("web panel ID"),
    "JS_LOCAL_TOGGLE_WEBPANEL": LocalAction("web panel ID"),
    # The interval becomes the reload alarm's period; zero is not a period.
    "PERIODIC_RELOAD": LocalAction("interval in minutes", integer=True, positive=True),
    "PERIODIC_RELOAD_DISABLE": LocalAction("'all' or any other text"),
}

# Never dispatched, whatever the caller asks. The reasons are reported with
# the rejection.
DENIED = {
    "COMMAND_EXIT": "quits the browser",
    "COMMAND_QUIT_MAC_MAYBE_WARN": "quits the browser",
    "COMMAND_CLOSE_WINDOW": "closing the last window may quit the browser",
    # Both handlers can close windows in 8.2.4133.94; see the version-scoped
    # static trace in docs/VIVALDI_CONTROL_SURFACE.md, "Tab-close lifecycle".
    "COMMAND_CLOSE_TAB": "can close a window; closing the last window may quit the browser",
    "COMMAND_TAB_STACK_CLOSE": "can close a window; closing the last window may quit the browser",
    "COMMAND_MAIL_DELETE_PERMANENTLY": "permanently deletes mail",
    "COMMAND_EXPORT_PASSWORDS": "exports saved passwords",  # pragma: allowlist secret
    "COMMAND_MANAGE_PEOPLE": "opens profile management",
    "COMMAND_NEW_GUEST_WINDOW": "switches to a guest session",
    "JS_LOCAL_CLEAR_CLOSED_TABS": "empties the closed tabs list",
    "JS_LOCAL_CLEAR_CLOSED_WEBPANELS": "empties the closed web panels list",
    "JS_LOCAL_ACTIVATE_WORKSPACE": (
        "creates a tab for an unknown workspace ID; use workspace switch, which checks the ID"
    ),
}


def command_list() -> list[dict[str, object]]:
    """Every known name with its kind, parameter and whether it may be dispatched."""
    entries: list[dict[str, object]] = []
    for name in sorted(REGISTERED_COMMANDS | LOCAL_ACTIONS.keys()):
        action = LOCAL_ACTIONS.get(name)
        entries.append(
            {
                "name": name,
                "kind": "command" if action is None else "local_action",
                "parameter": None if action is None else action.parameter,
                "allowed": name not in DENIED,
            }
        )
    return entries
